#!/usr/bin/env python3
"""make_scenario.py — a HUGSIM scenario that replays one converted PAI clip as recorded.

    python3 pai/make_scenario.py <scene_dir> <source_dir> <out.yaml> [--mode rec_02] [--min-track-s 1.0]

<scene_dir> is the export pai/train.sh wrote (data/scenes/pai/<name>), after pai/export_actors.py
baked its vehicles into <scene_dir>/actors/; <source_dir> is the pai/load_ncore.py output whose
meta_data.json holds the recorded front-camera poses (HUGSIM's world origin is the first one).

The scenario is the automatic version of configs/pai/ac73935a-rec-02.yaml, so that every clip
is replayed the way AlpaSim replays it:
  - ego: starts at the first front-camera pose, heading along it, no steering, at the recorded
    speed (mean over the first 0.5 s; 0 below 0.3 m/s, as on ac73935a's standstill start);
  - recorded traffic: every reconstructed moving vehicle whose fitted track spans at least
    --min-track-s, replayed by UnicyclePlanner on its own path with its original timing
    (speed 1.0), in its own reconstructed appearance (actors/track_<id>, height from
    actors.json); shorter tracks are fragments and are left out;
  - no HD map, no inserted vehicles.
HUGSIM does not read `target`; it is kept for parity with the shipped scenarios.
"""
import argparse
import json
import math
import os

ap = argparse.ArgumentParser()
ap.add_argument("scene_dir")
ap.add_argument("source_dir")
ap.add_argument("out")
ap.add_argument("--mode", default="rec_02")
ap.add_argument("--min-track-s", type=float, default=1.0)
ap.add_argument("--speed-window-s", type=float, default=0.5)
a = ap.parse_args()

scene = os.path.abspath(a.scene_dir)
name = os.path.basename(scene.rstrip("/"))
meta = json.load(open(os.path.join(a.source_dir, "meta_data.json")))
front = [f for f in meta["frames"] if "/CAM_FRONT/" in f["rgb_path"]]
t0, p0 = front[0]["timestamp"], [r[3] for r in front[0]["camtoworld"][:3]]
win = [f for f in front if 0 < f["timestamp"] - t0 <= a.speed_window_s + 1e-6]
if win:
    f = win[-1]
    p = [r[3] for r in f["camtoworld"][:3]]
    v = math.hypot(p[0] - p0[0], p[2] - p0[2]) / (f["timestamp"] - t0)   # ground plane: x right, z forward
else:
    v = 0.0
start_velo = round(v, 2) if v >= 0.3 else 0
path_m = sum(math.hypot(b["camtoworld"][0][3] - c["camtoworld"][0][3], b["camtoworld"][2][3] - c["camtoworld"][2][3])
             for c, b in zip(front[:-1], front[1:]))

actors = json.load(open(os.path.join(scene, "actors", "actors.json")))
kept, dropped = [], []
for tid, info in sorted(actors.items(), key=lambda kv: int(kv[0])):
    span = info["track_s"][1] - info["track_s"][0]
    (kept if span >= a.min_track_s else dropped).append((int(tid), info, span))

lines = [
    f"# {name} as recorded (generated by pai/make_scenario.py; edit the generator, not this file).",
    f"# Ego: first front-camera pose, recorded start speed {v:.2f} m/s over the first {a.speed_window_s} s"
    f" -> start_velo {start_velo}; recorded path {path_m:.1f} m.",
    f"# Recorded traffic in its own appearance (pai/export_actors.py), UnicyclePlanner, original timing:"
    f" tracks {', '.join(str(t) for t, _, _ in kept) or 'none'}"
    + (f"; left out as fragments (< {a.min_track_s} s): {', '.join(f'{t} ({s:.1f} s)' for t, _, s in dropped)}" if dropped else "")
    + ".",
    f"mode: {a.mode}",
]
if kept:
    lines.append("plan_list:")
    for tid, info, _ in kept:
        lines.append(f"- [0.0, 0.0, {info['height']}, 0.0, 0.0, \"{scene}/actors/track_{tid}\", UnicyclePlanner, {{uc_id: {tid}, speed: 1.0}}]")
else:
    lines.append("plan_list: []")
lines += [
    "iteration: 30000", "sh_degree: 3", "load_HD_map: false", "white_background: false", "data_device: cpu",
    "data_type: nuscenes", "start_euler:", "- 0.0", "- 0.0", "- 0.0", "start_ab:", "- 0.0", "- 0.0",
    f"start_velo: {start_velo}", "start_steer: 0", "target: 60", f"scene_name: {name}", "affine: false",
    "quiet: false", "ignore_dynamic: false", "unicycle: false",
]
os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
open(a.out, "w").write("\n".join(lines) + "\n")
print(f"{a.out}: start_velo {start_velo} (measured {v:.2f} m/s), path {path_m:.1f} m, "
      f"{len(kept)} recorded vehicles, {len(dropped)} fragments left out")
